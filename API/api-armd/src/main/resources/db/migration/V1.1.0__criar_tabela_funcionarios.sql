CREATE TABLE FUNCIONARIOS(
NMR_CRACHA BIGINT PRIMARY KEY IDENTITY,
NOME VARCHAR(80) NOT NULL,
CPF VARCHAR(11) NOT NULL,
SETOR VARCHAR(25),
STATUS VARCHAR(20),
DATA_NASCIMENTO DATE,
DATA_ADMISSAO DATE,
CEP VARCHAR(10),
RUA VARCHAR(30),
NMR_ENDERECO BIGINT,
BAIRRO VARCHAR(30),
TELEFONE VARCHAR(15),
EMAIL VARCHAR(50)
)