CREATE TABLE CLIENTES(
COD_CLIENTE BIGINT PRIMARY KEY IDENTITY,
NOME VARCHAR(80) NOT NULL,
CPF VARCHAR(11) NOT NULL,
EMAIL VARCHAR(50),
TELEFONE VARCHAR(15),
DATA_NASCIMENTO DATE,
GENERO VARCHAR(10),
LOGRADOURO VARCHAR(30),
BAIRRO VARCHAR(30),
NMR_ENDERECO BIGINT,
COMPLEMENTO VARCHAR(10),
PAIS VARCHAR(15),
CIDADE VARCHAR(40),
ESTADO VARCHAR(40),
CEP VARCHAR(10)
)